const ISSUANCE_A = "0631381B71048C4D35D2044917EE3C26F60E6CA8FC954A71";
const ISSUANCE_B = "064E278B6D15D1F5614B4D4E3183F835BCD62E7F6FD9FFD8";

// SendMax (Amount type, field 9) holding an MPT amount of the given issuance.
const makeMptSendMax = (issuanceId: string) =>
  `69600000000000000001${issuanceId}`;

const parseHex = (hex: string) => parseMptIssuanceIds(hexaStringToBuffer(hex)!);

describe("parseMptIssuanceIds", () => {
  it.each([
    ["an MPT Payment", MPT_PAYMENT, [ISSUANCE_A]],
    ["an MPT Clawback", MPT_CLAWBACK, [ISSUANCE_B]],
    ["an MPTokenAuthorize", MPT_AUTHORIZE, [ISSUANCE_A]],
    [
      "an MPTokenIssuanceSet",
      MPT_ISSUANCE_SET,
      ["06250C1982A2A3C10B2AD7917E90F6538BD18553EAE55AEF"],
    ],
    [
      "an MPTokenIssuanceDestroy",
      MPT_ISSUANCE_DESTROY,
      ["0631381671048C4D35D2044917EE3C26F60E6CA8FC954A71"],
    ],
    [
      "an OfferCreate with an MPT amount",
      OFFER_CREATE_MPT_AMOUNT,
      [ISSUANCE_A],
    ],
  ])("should return the issuance ID of %s", (_label, hex, expected) => {
    expect(parseHex(hex)).toStrictEqual(expected);
  });

  it.each([
    ["an XRP Payment", XRP_PAYMENT],
    ["an IOU Payment with paths", IOU_PAYMENT_WITH_PATHS],
    ["a Payment with arrays", PAYMENT_WITH_MEMOS],
    ["an MPTokenIssuanceCreate", MPT_ISSUANCE_CREATE],
  ])("should return no issuance ID for %s", (_label, hex) => {
    expect(parseHex(hex)).toStrictEqual([]);
  });

  it("should return two distinct IDs in transaction order", () => {
    expect(parseHex(MPT_PAYMENT + makeMptSendMax(ISSUANCE_B))).toStrictEqual([
      ISSUANCE_A,
      ISSUANCE_B,
    ]);
  });

  it("should return an ID once when the transaction holds it twice", () => {
    expect(parseHex(MPT_PAYMENT + makeMptSendMax(ISSUANCE_A))).toStrictEqual([
      ISSUANCE_A,
    ]);
  });

  it("should return nothing for a payload cut inside the MPT amount", () => {
    expect(parseHex(MPT_PAYMENT.slice(0, 80))).toStrictEqual([]);
  });

  it("should return nothing for a Hash160 field, a type the app cannot measure", () => {
    expect(parseHex(`${MPT_PAYMENT}0111${"00".repeat(20)}`)).toStrictEqual([]);
  });

  it("should return nothing for an empty payload", () => {
    expect(parseMptIssuanceIds(new Uint8Array())).toStrictEqual([]);
  });
});
